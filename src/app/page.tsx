import Link from "next/link";
import { listLibrary } from "@/lib/library";
import { listRecentGenerated } from "@/lib/store";
import { directory, findInDirectory } from "@/lib/directory";
import { SearchBox } from "@/components/SearchBox";
import { DirectoryExplorer } from "@/components/DirectoryExplorer";
import { GuideCard } from "@/components/GuideCard";
import { DifficultyBadge } from "@/components/badges";
import type { Difficulty } from "@/lib/types";

export const dynamic = "force-dynamic";

export default async function Home() {
  const [library, recent] = await Promise.all([listLibrary(), listRecentGenerated(9)]);

  // Map directory entries to guides that already exist (library or generated).
  const guideSlugs: Record<string, string> = {};
  for (const g of [...recent.map((r) => ({ slug: r.slug, name: r.name })), ...library.map((g) => ({ slug: g.slug, name: g.app.name }))]) {
    const d = findInDirectory(g.name);
    if (d) guideSlugs[d.slug] = g.slug;
  }
  const librarySlugs = library.map((g) => ({ slug: g.slug, name: g.app.name }));
  const recentOnly = recent.filter((r) => !library.some((g) => g.slug === r.slug));

  return (
    <div className="mx-auto max-w-5xl px-4">
      {/* Hero */}
      <section className="py-12 sm:py-16 max-w-3xl">
        <h1 className="text-3xl sm:text-4xl font-semibold tracking-tight leading-tight">
          How long until your users can connect <span className="text-accent">that app</span> to your agent?
        </h1>
        <p className="mt-4 text-[17px] text-foreground/80 leading-relaxed">
          Some OAuth apps take ten minutes. Others need a security assessment and weeks of review. Look up an app to see the
          path to production: steps, who does each one, the wait for approval, what blocks people, and how well each claim
          is supported.
        </p>
        <div className="mt-6">
          <SearchBox librarySlugs={librarySlugs} />
        </div>
        <p className="mt-3 text-xs text-muted">
          Not in the library? A research agent reads the provider&apos;s docs, probes their OAuth endpoints, and writes a
          shareable guide live, with every quote checked against its source. <Link href="/method" className="underline">How it works</Link>
        </p>
      </section>

      {/* Library */}
      <section id="library" className="scroll-mt-20">
        <div className="flex items-end justify-between gap-4">
          <div>
            <h2 className="text-xl font-semibold tracking-tight">Library</h2>
            <p className="text-sm text-muted mt-0.5">Researched in depth and checked against primary sources. Chosen to cover the range of setup paths.</p>
          </div>
          <div className="hidden sm:flex gap-1.5">
            {(["easy", "moderate", "hard", "very_hard"] as Difficulty[]).map((d) => <DifficultyBadge key={d} d={d} />)}
          </div>
        </div>
        <div className="mt-5 grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
          {library.map((g) => <GuideCard key={g.slug} g={g} />)}
        </div>
        {!library.length ? <p className="text-sm text-muted">Library guides are being researched.</p> : null}
      </section>

      {recentOnly.length ? (
        <section className="mt-12">
          <h2 className="text-xl font-semibold tracking-tight">Recently generated by the agent</h2>
          <p className="text-sm text-muted mt-0.5">Live guides other developers asked for. Lighter research than the library; check the evidence badges.</p>
          <ul className="mt-4 grid gap-2 sm:grid-cols-2 lg:grid-cols-3">
            {recentOnly.map((r) => (
              <li key={r.slug}>
                <Link href={`/guides/${r.slug}`} className="flex items-center justify-between rounded-lg border border-line bg-card px-3 py-2 text-sm hover:border-accent/50">
                  <span className="font-medium">{r.name}</span>
                  <DifficultyBadge d={r.difficulty as Difficulty} />
                </Link>
              </li>
            ))}
          </ul>
        </section>
      ) : null}

      {/* Directory */}
      <section id="directory" className="scroll-mt-20 mt-12 mb-16">
        <h2 className="text-xl font-semibold tracking-tight">Every OAuth app on Composio</h2>
        <p className="text-sm text-muted mt-0.5 max-w-3xl">
          {directory.counts.total} apps support OAuth. For {directory.counts.managed}, Composio supplies the OAuth app.
          For the other {directory.counts.bringYourOwn}, you must bring your own, and those are what this library is for.{" "}
          {directory.counts.bringYourOwnMcp} of them are remote MCP servers. In our read-only check of 45 of those, 42
          advertised Dynamic Client Registration, so an agent can likely create the OAuth client itself.{" "}
          <Link href="/method#mcp" className="underline">See the check</Link>.
        </p>
        <div className="mt-5">
          <DirectoryExplorer apps={directory.apps} guideSlugs={guideSlugs} />
        </div>
      </section>
    </div>
  );
}
